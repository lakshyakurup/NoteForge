import type { QuizQuestion } from "@/lib/ai";

/**
 * Client-side PDF export using the browser print dialog + a temporary printable view.
 * No extra dependency required — works offline and produces a real PDF via "Save as PDF".
 */
function openPrintWindow(title: string, bodyHtml: string) {
  const win = window.open("", "_blank", "noopener,noreferrer,width=800,height=900");
  if (!win) {
    alert("Please allow pop-ups to export the PDF.");
    return;
  }

  win.document.write(`<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8" />
  <title>${escapeHtml(title)}</title>
  <style>
    * { box-sizing: border-box; }
    body {
      font-family: system-ui, -apple-system, Segoe UI, Roboto, sans-serif;
      line-height: 1.5;
      color: #111;
      max-width: 720px;
      margin: 0 auto;
      padding: 32px 24px;
    }
    h1 { font-size: 1.5rem; margin: 0 0 4px; }
    .meta { color: #666; font-size: 0.85rem; margin-bottom: 24px; }
    h2 { font-size: 1.1rem; margin: 24px 0 8px; border-bottom: 1px solid #ddd; padding-bottom: 4px; }
    .q { margin-bottom: 20px; page-break-inside: avoid; }
    .q-num { font-weight: 600; color: #4338ca; }
    .options { margin: 6px 0 6px 16px; }
    .answer { color: #047857; font-size: 0.9rem; margin-top: 4px; }
    .explanation { color: #555; font-size: 0.85rem; }
    .card { border: 1px solid #ddd; border-radius: 8px; padding: 12px; margin-bottom: 12px; page-break-inside: avoid; }
    ul { margin: 4px 0 4px 18px; }
    @media print {
      body { padding: 0; }
      .no-print { display: none; }
    }
  </style>
</head>
<body>
  <h1>${escapeHtml(title)}</h1>
  <p class="meta">Generated by NoteForge · ${new Date().toLocaleString()}</p>
  ${bodyHtml}
  <p class="no-print" style="margin-top:32px">
    <button onclick="window.print()" style="padding:8px 16px;font-size:14px;cursor:pointer">
      Print / Save as PDF
    </button>
  </p>
  <script>setTimeout(() => window.print(), 300);</script>
</body>
</html>`);
  win.document.close();
}

function escapeHtml(s: string) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

export function exportQuizPdf(questions: QuizQuestion[]) {
  const body = questions
    .map((q, i) => {
      const opts =
        q.type === "mcq" && q.options
          ? `<div class="options">${q.options
              .map((o) => `• ${escapeHtml(o)}`)
              .join("<br/>")}</div>`
          : "";
      return `<div class="q">
        <div><span class="q-num">Q${i + 1}.</span> ${escapeHtml(q.question)}</div>
        ${opts}
        <div class="answer"><strong>Answer:</strong> ${escapeHtml(q.answer)}</div>
        ${q.explanation ? `<div class="explanation">${escapeHtml(q.explanation)}</div>` : ""}
      </div>`;
    })
    .join("");

  openPrintWindow("NoteForge — Quiz", body);
}

export function exportConceptsPdf(
  concepts: {
    title: string;
    summary: string;
    keyPoints?: string[];
    analogies?: string[];
  }[]
) {
  const body = concepts
    .map(
      (c) => `<div class="card">
      <strong>${escapeHtml(c.title)}</strong>
      <p>${escapeHtml(c.summary)}</p>
      ${c.keyPoints?.length ? `<ul>${c.keyPoints.map((p) => `<li>${escapeHtml(p)}</li>`).join("")}</ul>` : ""}
      ${c.analogies?.length ? `<p style="font-style:italic;color:#555">Analogy: ${escapeHtml(c.analogies.join(" · "))}</p>` : ""}
    </div>`
    )
    .join("");

  openPrintWindow("NoteForge — Concept Breakdown", body);
}

export function exportRevisionPdf(pack: {
  cheatSheet?: string;
  flashcards?: { front: string; back: string }[];
  highYield?: string[];
}) {
  let body = "";
  if (pack.cheatSheet) {
    body += `<h2>Cheat Sheet</h2><pre style="white-space:pre-wrap;font-family:inherit">${escapeHtml(pack.cheatSheet)}</pre>`;
  }
  if (pack.flashcards?.length) {
    body += `<h2>Flashcards</h2>`;
    body += pack.flashcards
      .map(
        (fc) =>
          `<div class="card"><strong>${escapeHtml(fc.front)}</strong><br/>${escapeHtml(fc.back)}</div>`
      )
      .join("");
  }
  if (pack.highYield?.length) {
    body += `<h2>High-Yield Points</h2><ul>${pack.highYield
      .map((h) => `<li>${escapeHtml(h)}</li>`)
      .join("")}</ul>`;
  }
  openPrintWindow("NoteForge — Revision Pack", body);
}
